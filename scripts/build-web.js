'use strict';
/*
 * Builds the browser version of Ender into site/.
 *
 * The whole app already divides into logic that knows nothing about its host
 * (src/core) and a view layer that only ever talks to `window.ender`
 * (src/renderer). The desktop serves that object over IPC from the main
 * process; the web build serves it from src/web, in the page. So this is not
 * a port: it is the same two halves with a different piece in the middle, and
 * every calculation in a report comes from the same file either way.
 *
 * The shared half is CommonJS, which a browser has no loader for, so each
 * module is wrapped in a function and written into modules.js with a tiny
 * require alongside it. The wrapping is the only thing done to the source --
 * no transpiling, no minifying, no tree shaking -- because the point of
 * sharing the files is lost the moment what ships stops being what was
 * tested. The result is readable in devtools, with original line numbers.
 *
 *   node scripts/build-web.js [outDir]
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DEFAULT_OUT = path.join(ROOT, 'site');

/* Every .js under these, keyed by the path a require() would name. */
const MODULE_DIRS = ['src/core', 'src/web'];

/* Modules that exist only for the desktop. Listing them is deliberate: the
 * build should fail loudly on an unknown import rather than silently ship a
 * module that reaches for the file system. */
const SKIP = new Set(['src/web/boot.js']);

/* Plain browser scripts, loaded in this order after window.ender exists. */
const VIEW_SCRIPTS = [
  'util.js',
  'views/workflow.js',
  'views/report.js',
  'views/library.js',
  'app.js'
];

const DEMO = ['DEMO_ALPHA_LN1_Settings.html', 'DEMO_BRAVO_LN1_Settings.html'];

function listJs(dir) {
  const out = [];
  const base = path.join(ROOT, dir);
  for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
    if (entry.isDirectory() || !entry.name.endsWith('.js')) continue;
    const rel = dir + '/' + entry.name;
    if (SKIP.has(rel)) continue;
    out.push(rel);
  }
  return out;
}

/** 'src/core/complex.js' -> 'core/complex', which is what require() resolves to. */
const idOf = (rel) => rel.replace(/^src\//, '').replace(/\.js$/, '');

let OUT = DEFAULT_OUT;

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function write(rel, text) {
  const target = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, text);
  return target;
}

/*
 * Wrap a module body. The newline before the source matters: it keeps every
 * line of the original on its own line, so a stack trace from the browser
 * still points at a line number that means something in the real file.
 */
function wrap(id, source) {
  return "__m['" + id + "'] = function (require, module, exports) {\n" +
    source.replace(/\r\n/g, '\n').replace(/\n*$/, '\n') +
    '};\n';
}

function build(outDir) {
  OUT = path.resolve(outDir || DEFAULT_OUT);
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  /* ------------------------------------------------------- modules --- */

  const files = MODULE_DIRS.flatMap(listJs);
  const modules = "/*\n * Generated by scripts/build-web.js -- do not edit.\n *\n" +
    " * Each body below is the unmodified source of the file named above it,\n" +
    " * wrapped so a browser can load it. Line numbers inside each module match\n" +
    " * the original file.\n */\n" +
    "window.__enderModules = {};\n(function () {\n  var __m = window.__enderModules;\n\n" +
    files.map((rel) => '/* ' + rel + ' */\n' + wrap(idOf(rel), fs.readFileSync(path.join(ROOT, rel), 'utf8'))).join('\n') +
    '}());\n';
  write('modules.js', modules);

  /* -------------------------------------------------- the view layer --- */

  for (const rel of VIEW_SCRIPTS) {
    copy(path.join(ROOT, 'src/renderer', rel), path.join(OUT, rel));
  }
  copy(path.join(ROOT, 'src/renderer/styles.css'), path.join(OUT, 'styles.css'));
  copy(path.join(ROOT, 'src/web/index.html'), path.join(OUT, 'index.html'));
  copy(path.join(ROOT, 'src/web/boot.js'), path.join(OUT, 'boot.js'));

  /*
   * The view layer loads the plot geometry from a global, the way a script
   * tag gives it on the desktop. In this build the module loader provides it,
   * so the file is not copied as a script -- it is already in modules.js.
   */

  /* ------------------------------------------------------- the rest --- */

  copy(
    path.join(ROOT, 'node_modules/pdf-lib/dist/pdf-lib.min.js'),
    path.join(OUT, 'vendor/pdf-lib.min.js')
  );
  for (const name of DEMO) {
    copy(path.join(ROOT, 'samples', name), path.join(OUT, 'samples', name));
  }

  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  write('manifest.js',
    '/* Generated by scripts/build-web.js -- do not edit. */\n' +
    'window.__enderManifest = ' + JSON.stringify({
      version,
      built: new Date().toISOString(),
      scripts: VIEW_SCRIPTS,
      modules: files.map(idOf)
    }, null, 2) + ';\n');

  // Pages serves this from a project path, so nothing may assume a root URL.
  write('.nojekyll', '');

  return { files, version };
}

if (require.main === module) {
  const { files, version } = build(process.argv[2]);
  console.log('web build -> ' + OUT);
  console.log('  ' + files.length + ' shared modules, ' + VIEW_SCRIPTS.length + ' view scripts, v' + version);
}

module.exports = { build, idOf, VIEW_SCRIPTS };
